def menu():
    return random.choice(MENUS)

def fill(t):
    m = menu()
    return t.replace("{m}", m)

rows = []
for _ in range(5000):
    r = random.random()
    labels = {t: 0 for t in TYPES}
    noise = 0
    if r < 0.08:                                   # 노이즈
        text = random.choice(NOISE)
        if random.random() < 0.3:
            text = text + " " + random.choice(NOISE)
        noise = 1
    elif r < 0.66:                                 # 긍정
        parts = [fill(random.choice(PRAISE_MENU)) for _ in range(random.randint(0, 2))]
        parts += random.sample(PRAISE_OTHER, random.randint(1 if not parts else 0, 2))
        random.shuffle(parts)
        text = ". ".join(parts) + random.choice(POS_END)
    elif r < 0.84:                                 # 부정 (1~2 유형)
        ts = random.sample(TYPES, 1 if random.random() < 0.65 else 2)
        body = [fill(random.choice(COMPLAIN[t])) for t in ts]
        for t in ts: labels[t] = 1
        text = random.choice(NEG_START) + ". ".join(body) + random.choice(NEG_END)
    else:                                          # 혼합: 칭찬 + 가벼운 불만
        t = random.choice(TYPES)
        labels[t] = 1
        good = fill(random.choice(PRAISE_MENU)) if random.random() < 0.6 else random.choice(PRAISE_OTHER)
        text = good + ". " + random.choice(CONNECT) + fill(random.choice(COMPLAIN[t]))
    rows.append(dict(text=text.strip(), is_noise=noise, **labels))

df = pd.DataFrame(rows).drop_duplicates("text")
df.to_csv("train_reviews.csv", index=False, encoding="utf-8-sig")
